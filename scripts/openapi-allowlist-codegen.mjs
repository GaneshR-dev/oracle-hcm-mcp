#!/usr/bin/env node
/**
 * Generate allowlist root suggestions from a tenant ADF describe dump or OpenAPI-ish JSON.
 * Usage:
 *   node scripts/openapi-allowlist-codegen.mjs --input describe.json [--out generated-allowlist.ts]
 *   ORACLE_HCM_BASE_URL=... ORACLE_HCM_USERNAME=... ORACLE_HCM_PASSWORD=... \
 *     node scripts/openapi-allowlist-codegen.mjs --fetch
 *
 * Unofficial — does not claim full Fusion OpenAPI coverage. CE/AI paths stay blocked.
 */
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
function flag(name, def) {
  const i = args.indexOf(name);
  if (i < 0) return def;
  return args[i + 1] ?? def;
}
const has = (name) => args.includes(name);

const BLOCKED = [/ce\//i, /generative.?ai/i, /\/ai\//i, /oracle.?internal/i, /\/fai\//i, /llm/i];

function rootsFromDescribe(doc) {
  const roots = new Set();
  const visit = (obj) => {
    if (!obj || typeof obj !== 'object') return;
    if (Array.isArray(obj)) {
      for (const x of obj) visit(x);
      return;
    }
    for (const [k, v] of Object.entries(obj)) {
      if (typeof v === 'string') {
        const m = v.match(/(?:resources\/[^/]+\/)?([A-Za-z][A-Za-z0-9_]*)/);
        if (m && !BLOCKED.some((re) => re.test(v))) roots.add(m[1]);
      }
      if (k === 'name' || k === 'ResourceName' || k === 'collection' || k === 'path') {
        if (typeof v === 'string' && /^[A-Za-z][A-Za-z0-9_]*$/.test(v)) roots.add(v);
      }
      visit(v);
    }
  };
  // OpenAPI paths
  if (doc.paths && typeof doc.paths === 'object') {
    for (const p of Object.keys(doc.paths)) {
      if (BLOCKED.some((re) => re.test(p))) continue;
      const seg = p.replace(/^\//, '').split('/')[0];
      if (seg && !seg.includes('{')) roots.add(seg);
    }
  }
  // ADF describe items
  const items = doc.items || doc.Resources || doc.resources || [];
  if (Array.isArray(items)) {
    for (const it of items) {
      const n = it.name || it.Name || it.resource || it.Resource;
      if (typeof n === 'string') roots.add(n);
    }
  }
  visit(doc);
  return [...roots].filter((r) => /^[A-Za-z][A-Za-z0-9_]*$/.test(r)).sort();
}

function emitTs(roots) {
  return `/**
 * AUTO-GENERATED allowlist candidate roots — review before merging into policy/allowlist.ts
 * Generated by scripts/openapi-allowlist-codegen.mjs
 * Unofficial — not Oracle OpenAPI.
 */
export const GENERATED_ALLOWED_ROOTS = [
${roots.map((r) => `  '${r}',`).join('\n')}
] as const;
`;
}

async function fetchDescribe() {
  const base = (process.env.ORACLE_HCM_BASE_URL || '').replace(/\/+$/, '');
  const version = process.env.ORACLE_HCM_API_VERSION || '11.13.18.05';
  if (!base) throw new Error('ORACLE_HCM_BASE_URL required for --fetch');
  const url = `${base}/resources/${version}/`;
  const headers = { Accept: 'application/json' };
  const u = process.env.ORACLE_HCM_USERNAME;
  const p = process.env.ORACLE_HCM_PASSWORD;
  if (u != null) headers.Authorization = `Basic ${Buffer.from(`${u}:${p || ''}`).toString('base64')}`;
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`Fetch describe failed: ${res.status}`);
  return res.json();
}

async function main() {
  let doc;
  if (has('--fetch')) {
    doc = await fetchDescribe();
  } else {
    const input = flag('--input', '');
    if (!input) {
      console.error('Usage: --input describe.json | --fetch');
      process.exit(1);
    }
    doc = JSON.parse(fs.readFileSync(input, 'utf8'));
  }
  const roots = rootsFromDescribe(doc);
  const out = flag('--out', path.join('src', 'policy', 'generated-allowlist.ts'));
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, emitTs(roots));
  console.error(`[codegen] wrote ${out} with ${roots.length} roots (review + merge manually)`);
  console.error('[codegen] CE/AI patterns remain blocked in allowlist.ts — do not weaken.');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
